const HTTP_ONLY_PREFIX = "#HttpOnly_";

/** Starting point for hand written cookie files, the comment documents the tab separated columns. */
export const NETSCAPE_FILE_TEMPLATE = [
	"# Netscape HTTP Cookie File",
	"# domain\tincludeSubdomains\tpath\tsecure\texpires\tname\tvalue",
	"",
].join("\n");

export interface NetscapeCookie {
	domain: string;
	includeSubdomains: boolean;
	path: string;
	secure: boolean;
	expires: number;
	name: string;
	value: string;
	httpOnly: boolean;
}

function flagToBoolean(value: string): boolean {
	return value.toUpperCase() === "TRUE";
}

function booleanToFlag(value: boolean): string {
	return value ? "TRUE" : "FALSE";
}

export function parseNetscapeCookies(content: string): NetscapeCookie[] {
	const cookies: NetscapeCookie[] = [];
	const lines = content.split(/\r?\n/);
	for (const line of lines) {
		const parsed = parseNetscapeCookieLine(line);
		if (parsed) cookies.push(parsed);
	}
	return cookies;
}

export function parseNetscapeCookieLine(line: string): NetscapeCookie | null {
	if (!line.trim()) return null;
	const httpOnly = line.startsWith(HTTP_ONLY_PREFIX);
	const raw = httpOnly ? line.slice(HTTP_ONLY_PREFIX.length) : line;
	if (!httpOnly && raw.trimStart().startsWith("#")) return null;
	const parts = raw.split("\t");
	if (parts.length < 7) return null;
	const [domain, includeSubdomains, path, secure, expires, name, ...valueParts] = parts;
	if (!domain || !name) return null;
	return {
		domain,
		includeSubdomains: flagToBoolean(includeSubdomains),
		path: path || "/",
		secure: flagToBoolean(secure),
		expires: Number(expires) || 0,
		name,
		value: valueParts.join("\t"),
		httpOnly,
	};
}

export function serializeNetscapeCookies(cookies: NetscapeCookie[]): string {
	const header = ["# Netscape HTTP Cookie File", "# This file was generated by ytdlp-gui. Do not edit.", ""];
	const lines = cookies.map((cookie) => {
		const prefix = cookie.httpOnly ? HTTP_ONLY_PREFIX : "";
		return [
			`${prefix}${cookie.domain}`,
			booleanToFlag(cookie.includeSubdomains),
			cookie.path,
			booleanToFlag(cookie.secure),
			String(cookie.expires || 0),
			cookie.name,
			cookie.value,
		].join("\t");
	});
	return [...header, ...lines, ""].join("\n");
}

export function cookieIdentityKey(cookie: NetscapeCookie): string {
	return `${cookie.domain}\0${cookie.path}\0${cookie.name}`;
}

export function summarizeNetscapeCookies(content: string): {
	cookieCount: number;
	domainCount: number;
	domains: string[];
} {
	const cookies = parseNetscapeCookies(content);
	const domainSet = new Set<string>();
	for (const cookie of cookies) domainSet.add(cookie.domain);
	const domains = [...domainSet];
	return {
		cookieCount: cookies.length,
		domainCount: domains.length,
		domains,
	};
}

export function mergeNetscapeCookieFiles(contents: string[]): string {
	const merged = new Map<string, NetscapeCookie>();
	for (const content of contents) {
		for (const cookie of parseNetscapeCookies(content)) {
			merged.set(cookieIdentityKey(cookie), cookie);
		}
	}
	return serializeNetscapeCookies([...merged.values()]);
}
