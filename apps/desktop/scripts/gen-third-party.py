"""Regenerates THIRD-PARTY.md at the repo root: fixed notices below plus the Rust crate licenses from `cargo metadata`.
Usage: python scripts/gen-third-party.py   (run in apps/desktop; needs cargo)"""
import collections, json, pathlib, subprocess

root = pathlib.Path(__file__).resolve().parents[3]
meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"], check=True, capture_output=True, text=True).stdout)
ws = set(meta["workspace_members"])
by = collections.defaultdict(list)
for p in meta["packages"]:
    if p["id"] not in ws:
        by[p["license"] or "UNKNOWN"].append(f'{p["name"]} {p["version"]}')

head = (root / "apps/desktop/scripts/third-party-head.md").read_text(encoding="utf-8")
out = [head, "\n## Rust crates (generated by scripts/gen-third-party.py)\n\n",
       f"{sum(len(v) for v in by.values())} crates, license expressions as declared in each crate's Cargo.toml.\n"]
for lic, names in sorted(by.items(), key=lambda kv: -len(kv[1])):
    out.append(f"\n### {lic} ({len(names)})\n\n" + ", ".join(sorted(set(names))) + "\n")
(root / "THIRD-PARTY.md").write_text("".join(out), encoding="utf-8", newline="\n")
